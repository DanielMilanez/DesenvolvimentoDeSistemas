int Function(int) somaParcial(int a){
  // Processamento da função primária
  return (int b){
    return a + b;
  };
}

void main(List<String> args) {
  print(somaParcial(2)(2)); 
  var somaProcessada = somaParcial(10);

  print(somaProcessada(2));
  print(somaProcessada(4));
  print(somaProcessada(5));
}

